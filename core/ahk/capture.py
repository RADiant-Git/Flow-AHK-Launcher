# -*- coding: utf-8 -*-
"""Захват физического нажатия.

Отличие от прежней реализации: запись можно ОТМЕНИТЬ. Раньше Escape был такой
же записываемой клавишей, а ввод блокировался на весь таймаут — пользователь
не мог ни отменить, ни свернуть. Теперь одиночный Escape отменяет захват;
привязать сам Escape по-прежнему можно через каталог клавиш или DSL-формулу
(осознанный размен, он описан в справке).

Также: модификаторы исключены из завершающих клавиш (иначе Ctrl+E записывалось
как просто Ctrl), состояние модификаторов читается из ih.EndMods, а не из
GetKeyState — это надежнее из-за рассинхронизации на доли секунды.
"""

import os
import subprocess
from dataclasses import dataclass

from core import config

KEY = "key"
CANCELLED = "cancelled"
TIMEOUT = "timeout"
ERROR = "error"

MARKER = "; FlowKey Manager capture v3"
TIMEOUT_TOKEN = "__TIMEOUT__"

# Скрипт содержит много фигурных скобок AHK, поэтому подстановка — по токенам,
# а не str.format: иначе {All} читается как поле формата и генерация падает.
_TEMPLATE = """; Auto-generated by FlowKey Manager. Не редактируйте вручную.
; FlowKey Manager capture v3
#Requires AutoHotkey v2.0
#SingleInstance Force

stdout := FileOpen("*", "w", "utf-8")

ih := InputHook("L1 T__TIMEOUT__")
ih.KeyOpt("{All}", "E")
; Модификаторы не должны завершать запись сами: иначе Ctrl+E поймает Ctrl.
ih.KeyOpt("{LCtrl}{RCtrl}{LAlt}{RAlt}{LShift}{RShift}{LWin}{RWin}", "-E")
; Блокируем и печатные, и служебные клавиши, чтобы записываемое сочетание
; не улетало в активное окно.
ih.VisibleNonText := false
ih.Start()

*MButton::Finish("MButton", "Middle Click")
*XButton1::Finish("XButton1", "Mouse 4 (Back)")
*XButton2::Finish("XButton2", "Mouse 5 (Forward)")

reason := ih.Wait()

if (reason = "Timeout") {
    Emit("Timeout")
    ExitApp(1)
}

key := ih.EndKey
mods := ih.EndMods

; Одиночный Escape без модификаторов — отмена. Escape с модификатором
; (Ctrl+Esc, Alt+Esc) записывается как обычный триггер.
if (key = "Escape" && mods = "") {
    Emit("Cancelled")
    ExitApp(2)
}

if (key = "") {
    Emit("Timeout")
    ExitApp(1)
}

prefix := ""
human := ""
if InStr(mods, "^") {
    prefix .= "^"
    human .= "Ctrl + "
}
if InStr(mods, "!") {
    prefix .= "!"
    human .= "Alt + "
}
if InStr(mods, "+") {
    prefix .= "+"
    human .= "Shift + "
}
if InStr(mods, "#") {
    prefix .= "#"
    human .= "Win + "
}

Emit(human . key . "|" . prefix . key)
ExitApp(0)

Finish(ahkName, humanName) {
    global ih, stdout
    ih.Stop()
    Emit(humanName . "|" . ahkName)
    ExitApp(0)
}

Emit(text) {
    global stdout
    stdout.Write(text)
    stdout.Close()
}
"""


def render(timeout: int) -> str:
    return _TEMPLATE.replace(TIMEOUT_TOKEN, str(int(timeout)))


def ensure_script(path: str = config.CAPTURE_SCRIPT,
                  timeout: int = config.CAPTURE_TIMEOUT) -> str:
    """Синхронизировать генерируемый скрипт с кодом. Возвращает путь."""
    wanted = render(timeout)
    current = None
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = None
    if current != wanted:
        folder = os.path.dirname(path)
        if folder and not os.path.isdir(folder):
            os.makedirs(folder, exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(wanted)
    return path


@dataclass
class Capture:
    kind: str
    trigger: str = ""
    human: str = ""
    message: str = ""

    @property
    def ok(self) -> bool:
        return self.kind == KEY and bool(self.trigger)

    @property
    def cancelled(self) -> bool:
        return self.kind == CANCELLED

    @property
    def timed_out(self) -> bool:
        return self.kind == TIMEOUT


def parse_output(text: str) -> Capture:
    body = str(text or "").strip()
    if not body:
        return Capture(TIMEOUT, message="AutoHotkey ничего не вернул")
    if body == "Cancelled":
        return Capture(CANCELLED)
    if body == "Timeout":
        return Capture(TIMEOUT)
    if "|" in body:
        human, trigger = body.split("|", 1)
        return Capture(KEY, trigger=trigger.strip(), human=human.strip())
    return Capture(KEY, trigger=body, human=body)


def run(executable: str, timeout: int = config.CAPTURE_TIMEOUT,
        script: str = config.CAPTURE_SCRIPT) -> Capture:
    """Дождаться одного нажатия. Блокирует ввод на время до `timeout` секунд."""
    from core.ahk import runtime as rt

    if not os.path.exists(executable):
        found = rt.locate_ahk()
        if not os.path.exists(found):
            return Capture(ERROR, message="AutoHotkey v2 не найден")
        executable = found

    path = ensure_script(script, timeout)
    try:
        proc = subprocess.run(
            [executable, path],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=timeout + 3,
            creationflags=subprocess.CREATE_NO_WINDOW,
        )
    except subprocess.TimeoutExpired:
        return Capture(TIMEOUT, message="Превышен общий таймаут захвата")
    except OSError as exc:
        return Capture(ERROR, message="Не удалось запустить AutoHotkey: %s"
                       % (exc.strerror or exc))

    captured = parse_output(proc.stdout)
    if captured.kind == ERROR:
        captured.message = (proc.stderr or captured.message).strip()[:200]
    return captured
